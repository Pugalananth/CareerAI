import React from "react";

import jsPDF from "jspdf";

import html2canvas from "html2canvas";

function Portfolio() {

  const user = JSON.parse(

    localStorage.getItem("user") || "{}"

  );

  const username = user?.name || "Student";

  const useremail = user?.email || "No Email";

  const downloadPDF = () => {

    const input = document.getElementById(

      "portfolio"

    );

    html2canvas(input).then((canvas) => {

      const img = canvas.toDataURL();

      const pdf = new jsPDF();

      pdf.addImage(

        img,

        "PNG",

        10,

        10,

        180,

        0

      );

      pdf.save("portfolio.pdf");

    });

  };

  const info = [

    {

      label: "Target Career",

      value: "Data Scientist",

      icon: "🎯"

    },

    {

      label: "ATS Score",

      value: "80%",

      icon: "📊"

    },

    {

      label: "Skills",

      value: "Python, Machine Learning, SQL",

      icon: "💡"

    },

    {

      label: "Roadmap",

      value: "Python → SQL → ML → Projects",

      icon: "🗺️"

    },

    {

      label: "Top Project",

      value: "Smart Career AI Recommendation System",

      icon: "🚀"

    },

  ];

  return (

    <div className="min-h-screen gradient-bg pt-28 pb-14 px-4">

      <div className="max-w-4xl mx-auto">

        {/* HEADER */}

        <div className="text-center mb-8">

          <div className="w-14 h-14 rounded-2xl bg-gradient-to-br from-amber-500 to-orange-600 flex items-center justify-center text-2xl mx-auto mb-4 shadow-xl">

            📊

          </div>

          <h1 className="text-3xl md:text-4xl font-black gradient-text mb-3">

            My Portfolio

          </h1>

          <p className="text-slate-400 text-sm">

            AI-powered personalised career portfolio

          </p>

        </div>

        {/* DOWNLOAD BUTTON */}

        <div className="flex justify-center mb-6">

          <button

            onClick={downloadPDF}

            className="px-6 py-3 rounded-2xl bg-gradient-to-r from-indigo-500 to-purple-600 text-white text-sm font-semibold shadow-xl hover:scale-105 transition-all duration-300"

          >

            ⬇️ Download PDF

          </button>

        </div>

        {/* PORTFOLIO CARD */}

        <div

          id="portfolio"

          className="glass rounded-3xl p-6"

        >

          {/* PROFILE */}

          <div className="flex items-center gap-4 mb-6 pb-5 border-b border-white/10">

            <div className="w-16 h-16 rounded-2xl bg-gradient-to-br from-indigo-500 to-violet-600 flex items-center justify-center text-white text-2xl font-black shadow-xl">

              {username.charAt(0).toUpperCase()}

            </div>

            <div>

              <h2 className="text-2xl font-black text-black">

                {username}

              </h2>

              <p className="text-slate-400 text-sm mt-1 flex items-center gap-2">

                📧 {useremail}

              </p>

              <span className="inline-block mt-3 px-3 py-1 rounded-xl bg-indigo-500/20 border border-indigo-400/20 text-indigo-300 text-xs">

                AI Career Aspirant

              </span>

            </div>

          </div>

          {/* INFO */}

          <div className="space-y-4">

            {info.map((item,i)=>(

              <div

                key={i}

                className="bg-[#1e293b] border border-white/10 rounded-2xl p-4 flex gap-4 items-start"

              >

                <div className="text-2xl">

                  {item.icon}

                </div>

                <div>

                  <p className="text-xs uppercase tracking-wider text-slate-500 font-semibold mb-1">

                    {item.label}

                  </p>

                  <p className="text-white text-sm font-medium">

                    {item.value}

                  </p>

                </div>

              </div>

            ))}

          </div>

          {/* FOOTER */}

          <div className="mt-6 pt-4 border-t border-white/10 text-center text-xs text-slate-500">

            Generated by CareerAI • {new Date().getFullYear()}

          </div>

        </div>

      </div>

    </div>

  );

}

export default Portfolio;